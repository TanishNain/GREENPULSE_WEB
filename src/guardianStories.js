export function getUnlockedStories(points = 0) {
  return GUARDIAN_STORIES.filter(
    (story) => Number(points) >= Number(story.unlockPoints || 0)
  );
}

export function getStoryById(id) {
  return GUARDIAN_STORIES.find((story) => story.id === id);
}

export function getChapterCount(story) {
  return story?.chapters?.length || 0;
}

export function getStoryText(story) {
  if (!story?.chapters) return "";

  return story.chapters
    .map((chapter) => `${chapter.title}\n\n${chapter.text.trim()}`)
    .join("\n\n");
}